import type { Aspect, CaptionStyle, Word } from "@/lib/types";
import { ASPECTS } from "@/lib/types";
import { buildLines, type CaptionLine } from "@/lib/captions/layout";
import { cssToAssColor } from "@/lib/captions/colors";

/**
 * Compiles captions into an Advanced SubStation Alpha (.ass) file that ffmpeg
 * burns in with the `subtitles` filter.
 *
 * Strategy: one Dialogue event PER WORD. Each event redraws the whole line but
 * only the spoken word carries highlight overrides. That makes the burned-in
 * output match the React preview (which does exactly the same thing) far more
 * closely than plain \k karaoke tags, and lets us support per-word boxes.
 */

export type AssOptions = {
  aspect: Aspect;
  /** Override output size (the renderer may export 720p while the doc says 1080p). */
  width?: number;
  height?: number;
  /** Shift every caption timing (e.g. clip was trimmed). */
  offsetMs?: number;
  /** Override vertical anchor, in % of height. */
  positionYPct?: number;
};

function assTime(ms: number): string {
  const totalCs = Math.max(0, Math.round(ms / 10));
  const cs = totalCs % 100;
  const totalSeconds = Math.floor(totalCs / 100);
  const s = totalSeconds % 60;
  const m = Math.floor(totalSeconds / 60) % 60;
  const h = Math.floor(totalSeconds / 3600);
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${h}:${pad(m)}:${pad(s)}.${pad(cs)}`;
}

function escapeAss(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/\{/g, "\\{")
    .replace(/\}/g, "\\}")
    .replace(/\r?\n/g, " ");
}

/** ASS accepts a comma-separated font fallback chain; the worker image installs these. */
function fontChain(style: CaptionStyle): string {
  return `${style.fontFamily},DejaVu Sans,Noto Sans,Arial`;
}

export function buildAss(words: Word[], style: CaptionStyle, opts: AssOptions): string {
  const width = opts.width ?? ASPECTS[opts.aspect].width;
  const height = opts.height ?? ASPECTS[opts.aspect].height;

  const fs = Math.max(8, Math.round((width * style.fontScale) / 100));
  const outline = Math.max(0, style.strokeScale * fs);
  const shadow = Math.max(0, style.shadow * fs * 0.1);
  const offset = opts.offsetMs ?? 0;

  const baseColor = cssToAssColor(style.textColor);
  const activeColor = cssToAssColor(style.activeTextColor);
  const strokeColor = cssToAssColor(style.strokeColor);
  const boxColor = cssToAssColor(style.highlightBg);
  // BorderStyle 3 draws a filled box behind the text; BackColour is that box.
  const boxBack = style.background ? cssToAssColor(style.backgroundFill, 0.72) : cssToAssColor("#000000", 0);
  const borderStyle = style.background ? 3 : 1;

  const lines = buildLines(words, style);
  const centerX = Math.round(width / 2);
  const anchorY = Math.round((height * (opts.positionYPct ?? style.positionYPct)) / 100);

  const header = `[Script Info]
; Generated by Reelforge
ScriptType: v4.00+
PlayResX: ${width}
PlayResY: ${height}
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: RF,${fontChain(style)},${fs},${baseColor},${boxColor},${strokeColor},${boxBack},${style.fontWeight >= 700 ? -1 : 0},0,0,0,100,100,${(style.letterSpacing * fs).toFixed(1)},0,${borderStyle},${outline.toFixed(1)},${shadow.toFixed(1)},5,0,0,0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text`;

  const events: string[] = [];

  // A little lead-in so a line is visible at the exact millisecond it starts.
  const LEAD_MS = 30;

  for (const line of lines) {
    line.words.forEach((word, wi) => {
      const start = word.s + offset - LEAD_MS;
      const nextWord = line.words[wi + 1];
      const end = (nextWord ? nextWord.s : Math.max(word.e, line.endMs)) + offset;
      if (end <= start) return;

      const tags = [
        "\\an5",
        `\\pos(${centerX},${anchorY})`,
        `\\fs${fs}`,
        `\\1c${baseColor}`,
        `\\3c${strokeColor}`,
        `\\bord${outline.toFixed(1)}`,
        `\\shad${shadow.toFixed(1)}`,
        "\\fad(40,40)",
      ].join("");

      events.push(
        `Dialogue: 0,${assTime(start)},${assTime(end)},RF,,0,0,0,,{${tags}}${renderLineText(line, wi, style, fs)}`,
      );
    });
  }

  return `${header}\n${events.join("\n")}\n`;
}

/**
 * Renders a full caption line as ASS text, applying highlight overrides to the
 * active word only. `{\r}` resets back to the style defaults.
 */
function renderLineText(line: CaptionLine, activeIdx: number, style: CaptionStyle, fs: number): string {
  return line.words
    .map((word, i) => {
      const raw = escapeAss(style.uppercase ? word.w.toUpperCase() : word.w);
      if (i !== activeIdx) return raw;

      const overrides: string[] = [];
      switch (style.highlight) {
        case "color":
          overrides.push(`\\1c${cssToAssColor(style.activeTextColor)}`);
          break;
        case "box":
          // Thick outline in the highlight colour reads as a pill behind the word.
          overrides.push(`\\3c${cssToAssColor(style.highlightBg)}\\bord${(fs * 0.42).toFixed(1)}\\shad0\\1c${cssToAssColor(style.activeTextColor)}`);
          break;
        case "underline":
          overrides.push(`\\u1\\1c${cssToAssColor(style.activeTextColor)}`);
          break;
        case "scale":
          overrides.push(`\\fscx112\\fscy112\\1c${cssToAssColor(style.activeTextColor)}`);
          break;
        case "none":
        default:
          break;
      }
      if (!overrides.length) return raw;
      return `{${overrides.join("")}}${raw}{\\r}`;
    })
    .join(" ");
}

/** Plain SRT export — handy for YouTube uploads and client handoff. */
export function buildSrt(words: Word[], style: CaptionStyle, offsetMs = 0): string {
  const srtTime = (ms: number) => {
    const safe = Math.max(0, ms);
    const h = Math.floor(safe / 3600000);
    const m = Math.floor(safe / 60000) % 60;
    const s = Math.floor(safe / 1000) % 60;
    const mmm = Math.round(safe % 1000);
    const pad = (n: number, len = 2) => String(n).padStart(len, "0");
    return `${pad(h)}:${pad(m)}:${pad(s)},${pad(mmm, 3)}`;
  };

  return buildLines(words, style)
    .map((line, i) => {
      const text = style.uppercase ? line.text.toUpperCase() : line.text;
      return `${i + 1}\n${srtTime(line.startMs + offsetMs)} --> ${srtTime(line.endMs + offsetMs)}\n${text}\n`;
    })
    .join("\n");
}
